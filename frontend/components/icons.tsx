// 轻量 SVG 图标集 (lucide 风格描边)。新布局不再用字符图标 (⧉/⟳/☾):
// 这些字形在缺字体的环境下会渲染成方块, SVG 跨平台一致。
import type { ReactNode, SVGProps } from "react";

type IconProps = Omit<SVGProps<SVGSVGElement>, "width" | "height" | "children"> & {
  size?: number;
};

function Svg({ size = 18, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

